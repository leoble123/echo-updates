import fs from "fs";
import os from "os";
import path from "path";
import crypto from "crypto";
import { clipboard, Notification, shell } from "electron";
import { Server } from "@server";
import { Loggable } from "@server/lib/logging/Loggable";

export type Clip = { text: string; at: number; from: string };
export type Drop = { id: string; name: string; size: number; at: number };

/** Socket events the phone and Echo Web listen for. */
export const CLIPBOARD_EVENT = "echo-clipboard";
export const DROP_EVENT = "echo-drop";

/** Larger clipboards aren't worth pushing around. */
const MAX_CLIP = 100_000;
/** Password managers mark what they copy with these (nspasteboard.org). */
const PRIVATE_TYPES = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
/** Files dropped in Send stay offered this long, then move to Sent. */
const OFFER_MS = 24 * 3600_000;

/** Turns any name into one safe to save under, keeping its extension. */
export const safeName = (raw: string): string => {
    const base = path.basename(String(raw ?? "").replace(/\\/g, "/"));
    const clean = base.replace(/[\u0000-\u001f:/]/g, "").replace(/^\.+/, "").trim().slice(-180);
    return clean || "file";
};

/** [dir]/[name], or "name 2.ext", "name 3.ext"… if it's taken. */
export const uniquePath = (dir: string, name: string): string => {
    const ext = path.extname(name);
    const stem = name.slice(0, name.length - ext.length);
    let candidate = path.join(dir, name);
    for (let i = 2; fs.existsSync(candidate); i++) candidate = path.join(dir, `${stem} ${i}${ext}`);
    return candidate;
};

/**
 * Universal Clipboard and file drop between the Mac, the phone and Echo Web.
 *
 * Clipboard: while it's on, what you copy on the Mac goes out to your devices,
 * and what they send lands on the Mac's clipboard. Things a password manager
 * marks as private are never sent.
 *
 * Files: what your devices send is saved to ~/Downloads/Echo. Anything you put
 * in ~/Downloads/Echo/Send to Phone is offered to them for a day, then moved
 * to its Sent folder.
 */
export class EchoHandoff extends Loggable {
    tag = "EchoHandoff";

    private static instance: EchoHandoff;

    static get() {
        EchoHandoff.instance ??= new EchoHandoff();
        return EchoHandoff.instance;
    }

    static inbox = path.join(os.homedir(), "Downloads", "Echo");

    static outbox = path.join(EchoHandoff.inbox, "Send to Phone");

    static sent = path.join(EchoHandoff.outbox, "Sent");

    private timer: NodeJS.Timeout = null;

    /** The latest clip from anywhere. */
    last: Clip = null;

    /** What the Mac's clipboard held at the last look, so changes stand out. */
    private seen: string = null;

    /** Files on offer, by id, with the size they had last time (to tell when a copy has finished). */
    private offered: Map<string, Drop & { file: string }> = new Map();

    private pending: Map<string, number> = new Map();

    get clipboardOn() {
        const v = Server().repo.getConfig("echo_clipboard_sync");
        return v === true || v === 1 || v === "1" || v === "true";
    }

    async setClipboardOn(on: boolean) {
        await Server().repo.setConfig("echo_clipboard_sync", on);
        this.seen = null;
    }

    start() {
        if (this.timer) return;
        try {
            fs.mkdirSync(EchoHandoff.sent, { recursive: true });
        } catch (ex: any) {
            this.log.debug(`Couldn't make the Echo folders: ${ex?.message}`);
        }
        this.timer = setInterval(() => {
            try {
                this.watchClipboard();
            } catch (ex: any) {
                this.log.debug(`Clipboard check failed: ${ex?.message}`);
            }
        }, 1500);
        // Folders change far less often than the clipboard.
        setInterval(() => this.watchOutbox(), 3000);
    }

    private announce(event: string, data: unknown) {
        Server().emitMessage(event, data, "normal", false);
    }

    // --- Clipboard ------------------------------------------------------------

    private watchClipboard() {
        if (!this.clipboardOn) return;
        const text = clipboard.readText();
        if (this.seen === null) {
            // The first look only learns what's there; it isn't news.
            this.seen = text;
            return;
        }
        if (text === this.seen) return;
        this.seen = text;
        if (!text || text.length > MAX_CLIP) return;
        const formats = clipboard.availableFormats();
        if (PRIVATE_TYPES.some(t => formats.includes(t))) return;
        this.last = { text, at: Date.now(), from: "mac" };
        this.announce(CLIPBOARD_EVENT, this.last);
    }

    /** Something copied on a device: onto the Mac's clipboard, and out to the others. */
    receiveClip(text: string, from: string): Clip {
        const clip = { text: String(text ?? "").slice(0, MAX_CLIP), at: Date.now(), from: safeName(from || "device") };
        if (!clip.text) throw new Error("Nothing to copy");
        clipboard.writeText(clip.text);
        this.seen = clip.text;
        this.last = clip;
        this.announce(CLIPBOARD_EVENT, clip);
        return clip;
    }

    // --- Files ----------------------------------------------------------------

    /** Saves a file a device sent into ~/Downloads/Echo and says so on the Mac. */
    receiveFile(tempPath: string, name: string, from: string): { name: string; size: number } {
        fs.mkdirSync(EchoHandoff.inbox, { recursive: true });
        const target = uniquePath(EchoHandoff.inbox, safeName(name));
        try {
            fs.renameSync(tempPath, target);
        } catch {
            // Across volumes a rename can't work; copy instead.
            fs.copyFileSync(tempPath, target);
            fs.unlink(tempPath, () => null);
        }
        const saved = { name: path.basename(target), size: fs.statSync(target).size };
        try {
            if (Notification.isSupported()) {
                const n = new Notification({ title: `From your ${from || "phone"}`, body: saved.name, silent: true });
                n.on("click", () => shell.showItemInFolder(target));
                n.show();
            }
        } catch {
            /* a notification is a nicety */
        }
        return saved;
    }

    private dropId(file: string, st: fs.Stats) {
        return crypto.createHash("sha1").update(`${file}|${st.size}|${st.mtimeMs}`).digest("hex").slice(0, 16);
    }

    /** Looks in Send to Phone: offers new files once they've stopped growing, retires old ones. */
    watchOutbox() {
        let names: string[];
        try {
            names = fs.readdirSync(EchoHandoff.outbox);
        } catch {
            return;
        }
        const present = new Set<string>();
        for (const n of names) {
            if (n.startsWith(".") || n === "Sent") continue;
            const file = path.join(EchoHandoff.outbox, n);
            let st: fs.Stats;
            try {
                st = fs.statSync(file);
            } catch {
                continue;
            }
            if (!st.isFile()) continue;
            present.add(file);
            const known = [...this.offered.values()].find(d => d.file === file);
            if (known) {
                if (Date.now() - known.at > OFFER_MS) this.retire(known.id);
                continue;
            }
            // Offered only once it's the same size twice running - a copy into the folder has finished.
            if (this.pending.get(file) !== st.size) {
                this.pending.set(file, st.size);
                continue;
            }
            this.pending.delete(file);
            const drop = { id: this.dropId(file, st), name: n, size: st.size, at: Date.now(), file };
            this.offered.set(drop.id, drop);
            this.announce(DROP_EVENT, { id: drop.id, name: drop.name, size: drop.size, at: drop.at });
        }
        for (const [id, d] of this.offered) if (!present.has(d.file)) this.offered.delete(id);
        for (const f of this.pending.keys()) if (!present.has(f)) this.pending.delete(f);
    }

    private retire(id: string) {
        const d = this.offered.get(id);
        if (!d) return;
        this.offered.delete(id);
        try {
            fs.mkdirSync(EchoHandoff.sent, { recursive: true });
            fs.renameSync(d.file, uniquePath(EchoHandoff.sent, d.name));
        } catch (ex: any) {
            this.log.debug(`Couldn't move ${d.name} to Sent: ${ex?.message}`);
        }
    }

    drops(): Drop[] {
        return [...this.offered.values()]
            .sort((a, b) => b.at - a.at)
            .map(({ id, name, size, at }) => ({ id, name, size, at }));
    }

    /** The file behind [id] - only ever one that's on offer. */
    dropFile(id: string): { file: string; name: string; size: number } | null {
        const d = this.offered.get(String(id));
        return d && fs.existsSync(d.file) ? { file: d.file, name: d.name, size: d.size } : null;
    }

    /** Done with: off the list and into Sent. */
    finish(id: string) {
        this.retire(String(id));
    }
}
